CREATE TABLE stock (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	product_id INTEGER NOT NULL,
	amount DOUBLE PRECISION NOT NULL,
	best_before_date DATE,
	purchased_date DATE DEFAULT CURRENT_DATE,
	stock_id TEXT NOT NULL,
	price DOUBLE PRECISION,
	open SMALLINT NOT NULL DEFAULT 0 CHECK(open IN (0, 1)),
	-- DATETIME upstream, but only ever holds a date and the OpenAPI spec says
	-- format: date. As TIMESTAMP, PostgreSQL would render it "2026-08-26 00:00:00"
	-- where SQLite returns "2026-08-26", changing the API response.
	opened_date DATE,
	row_created_timestamp TIMESTAMP DEFAULT date_trunc('second', LOCALTIMESTAMP),
	location_id INTEGER,
	shopping_location_id INTEGER,
	note TEXT
);

