-- PostgreSQL baseline schema: tables
--
-- Equivalent to the state SQLite reaches after migrations 0001-0255. PostgreSQL
-- installations start from here instead of replaying the SQLite migration history.
--
-- Type choices are constrained by API compatibility rather than by what is most natural
-- in PostgreSQL - see db/pgsql/README.md. In short: amounts are DOUBLE PRECISION (NUMERIC
-- would serialise as a JSON string), flags are SMALLINT holding 0/1 (BOOLEAN would
-- serialise as true/false), and both would break the documented response schemas.

CREATE TABLE api_keys (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	api_key TEXT NOT NULL UNIQUE,
	user_id INTEGER NOT NULL,
	expires TIMESTAMP,
	last_used TIMESTAMP,
	row_created_timestamp TIMESTAMP DEFAULT date_trunc('second', LOCALTIMESTAMP),
	key_type TEXT NOT NULL DEFAULT 'default',
	description TEXT
);

