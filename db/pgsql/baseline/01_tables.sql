	due_date DATE,
	done SMALLINT NOT NULL DEFAULT 0 CHECK(done IN (0, 1)),
	done_timestamp TIMESTAMP,
	category_id INTEGER,
	assigned_to_user_id INTEGER,
	row_created_timestamp TIMESTAMP DEFAULT date_trunc('second', LOCALTIMESTAMP)
);

