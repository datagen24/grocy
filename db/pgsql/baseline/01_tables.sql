CREATE TABLE tasks (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name TEXT NOT NULL,
	description TEXT,
	-- DATETIME upstream and documented as date-time, but the task form writes
	-- date('Y-m-d') only, so DATE reproduces the existing API response exactly.
